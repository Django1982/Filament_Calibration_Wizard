// ---------------------------------------------------------------------------
// Automated Calibration Pipeline — calibration asset registry (Stage 4).
//
// Maps each sliceable calibration step to the model it needs and resolves WHERE
// that model comes from, honoring the project's long-standing licensing stance:
// PerfectFit ships NO third-party calibration models. Sources, in priority:
//
//   1. user-provided file            — the user owns it; always allowed.
//   2. installed-slicer-resource     — the model shipped inside the user's own
//                                      Orca install (resources/calib/…); we
//                                      reference it, never redistribute it.
//   3. bundled                       — only assets whose license explicitly
//                                      permits redistribution (none ship today).
//   4. download                      — only when redistribution is permitted.
//   5. generated                     — Orca produces the geometry itself
//                                      (e.g. max volumetric speed); no file.
//
// A non-redistributable asset is NEVER served from a bundled/downloaded copy —
// only referenced from the user's own install or a file they supply.
//
// Pure module (no fs): resolution computes locations; the engine stage verifies
// the file exists and copies it. Gated behind the disabled flag.
// ---------------------------------------------------------------------------

