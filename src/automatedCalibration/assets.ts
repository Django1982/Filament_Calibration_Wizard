// --- resolution ------------------------------------------------------------

export interface AssetResolutionContext {
  /** The installed slicer's resource root, e.g. '…/OrcaSlicer/resources'. */
  slicerResourceRoot?: string;
  /** A file the user supplied for this step (always permitted). */
  userProvidedPath?: string;
  /** Whether downloading a redistributable asset is permitted right now. */
  allowDownload?: boolean;
}

export interface AssetResolution {
  available: boolean;
  stepId: CalibrationId;
  assetId: string | null;
  sourceKind: AssetSourceKind | null;
  /** Absolute path (bundled/installed/user) or URL (download), or null. */
  location: string | null;
  license: AssetLicenseMetadata | null;
  requiresParameterization: boolean;
  warnings: string[];
  /** What the user can do when nothing resolved. */
  remedy?: string;
}

/** Join a resource root and a relative path, matching the root's separator so
 *  the result is valid on the host OS (pure — no node 'path'). */
export function joinResourcePath(root: string, rel: string): string {
  const sep = root.includes('\\') && !root.includes('/') ? '\\' : root.includes('\\') ? '\\' : '/';
  const trimmedRoot = root.replace(/[\\/]+$/, '');
  const normalizedRel = rel.replace(/[\\/]+/g, sep);
  return `${trimmedRoot}${sep}${normalizedRel}`;
}

/**
 * Resolve where a step's calibration asset should come from. Never redistributes
 * a non-redistributable asset from a bundled/downloaded copy. Pure: does not
 * check the filesystem — the engine stage verifies existence at stage time.
 */
export function resolveAsset(stepId: CalibrationId, ctx: AssetResolutionContext = {}): AssetResolution {
  const def = CALIBRATION_ASSETS[stepId];
  if (!def) {
    return {
      available: false, stepId, assetId: null, sourceKind: null, location: null,
      license: null, requiresParameterization: false, warnings: [],
      remedy: 'No calibration asset is registered for this step.'
    };
  }
  const base = {
    stepId,
    assetId: def.id,
    license: def.license,
    requiresParameterization: def.requiresParameterization === true
  };

  // 1. User-provided always wins — the user owns the file.
  if (ctx.userProvidedPath) {
    return { ...base, available: true, sourceKind: 'user-provided', location: ctx.userProvidedPath, warnings: [] };
  }

  // 2. Generated by the slicer — no file needed.
  if (def.assetType === 'generated') {
    return { ...base, available: true, sourceKind: 'generated', location: null, warnings: [] };
  }

  // 3. The model shipped inside the user's own slicer install.
  if (def.slicerResourceRelPath && ctx.slicerResourceRoot) {
    return {
      ...base, available: true, sourceKind: 'installed-slicer-resource',
      location: joinResourcePath(ctx.slicerResourceRoot, def.slicerResourceRelPath), warnings: []
    };
  }

  // 4. Bundled — only if the license explicitly permits redistribution.
  if (def.bundledPath && def.license.redistributable) {
    return { ...base, available: true, sourceKind: 'bundled', location: def.bundledPath, warnings: [] };
  }

  // 5. Download — only a redistributable asset may be fetched automatically.
  if (def.downloadUrl && ctx.allowDownload && def.license.redistributable) {
    return { ...base, available: true, sourceKind: 'download', location: def.downloadUrl, warnings: [] };
  }

  // Nothing available: guide the user, honoring the no-redistribution rule.
  const remedy = def.downloadUrl
    ? `This model isn't redistributed by PerfectFit. Download it from ${def.downloadUrl} and select the file, or point PerfectFit at your OrcaSlicer installation.`
    : 'Select your OrcaSlicer installation so PerfectFit can use its calibration model, or supply the file yourself.';
  return {
    ...base, available: false, sourceKind: null, location: null,
    warnings: ['Calibration asset could not be resolved from an allowed source.'],
    remedy
  };
}
